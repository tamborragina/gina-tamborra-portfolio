let currentLanguage = 'it';
const grid = document.querySelector('#project-grid');
const langButton = document.querySelector('#language');

function renderProjects() {
  grid.innerHTML = projects.map((p, i) => {
    const image = p.images && p.images.length ? p.images[0] : '';
    const title = p.title;
    const category = currentLanguage === 'it' ? p.category_it : p.category_en;
    const meta = currentLanguage === 'it' ? p.meta_it : p.meta_en;
    const description = currentLanguage === 'it' ? p.it : p.en;
    return `<article class="project-card" id="${p.id}">
      <div class="project-image-wrap">
        ${image ? `<img class="project-image" src="${image}" alt="${title}" loading="${i < 2 ? 'eager' : 'lazy'}">` : ''}
        <span class="project-index">${String(i + 1).padStart(2, '0')}</span>
      </div>
      <div class="project-caption">
        <h3>${title}</h3><span class="project-arrow">↗</span>
        <div class="project-meta">${meta} · ${category}</div>
      </div>
      <p class="project-description">${description}</p>
    </article>`;
  }).join('');
}
function setLanguage(lang) {
  currentLanguage = lang;
  document.documentElement.lang = lang;
  langButton.textContent = lang === 'it' ? 'EN' : 'IT';
  document.querySelectorAll('[data-it][data-en]').forEach(el => {
    el.innerHTML = el.dataset[lang];
  });
  renderProjects();
}
langButton.addEventListener('click', () => setLanguage(currentLanguage === 'it' ? 'en' : 'it'));
renderProjects();
